package appstore

import (
	"context"
	"crypto/sha256"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// phpMyAdmin runs the official image's Apache on 127.0.0.1:<port> (host
// network, so it reaches every MySQL / MariaDB on loopback) and is served
// under /phpmyadmin/ by the panel's authenticated proxy. Each installed
// engine is one phpMyAdmin server, signed in as root ("config" auth): the
// panel session is the login, as with aaPanel's one-click phpMyAdmin.

// PMAPrefix is the URL path phpMyAdmin is served under.
const PMAPrefix = "/phpmyadmin"

func pmaEngine(app string) bool { return app == "mysql" || app == "mariadb" }

// pmaEngines lists the engines in phpMyAdmin server order (1-based).
func (sv *Service) pmaEngines(ctx context.Context) ([]Installed, error) {
	all, err := sv.list(ctx, "")
	if err != nil {
		return nil, err
	}
	out := []Installed{}
	for _, i := range all {
		if pmaEngine(i.App) {
			out = append(out, i)
		}
	}
	return out, nil
}

// PMAPort returns the loopback port of an installed phpMyAdmin (0 = none).
func (sv *Service) PMAPort(ctx context.Context) int {
	all, err := sv.list(ctx, "WHERE app = 'phpmyadmin'")
	if err != nil || len(all) == 0 {
		return 0
	}
	return all[0].Port
}

// PMAServers maps an engine's app id to its phpMyAdmin server number; it is
// empty when phpMyAdmin is not installed.
func (sv *Service) PMAServers(ctx context.Context) map[int64]int {
	out := map[int64]int{}
	if sv.PMAPort(ctx) == 0 {
		return out
	}
	engines, _ := sv.pmaEngines(ctx)
	for n, e := range engines {
		out[e.ID] = n + 1
	}
	return out
}

func phpQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

func (sv *Service) pmaConfig(ctx context.Context, secret string) (string, error) {
	engines, err := sv.pmaEngines(ctx)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("<?php\n// Generated by lmcwhm; rewritten when MySQL / MariaDB versions are installed or removed.\n")
	fmt.Fprintf(&b, "$cfg['blowfish_secret'] = %s;\n", phpQuote(fmt.Sprintf("%x", sha256.Sum256([]byte("pma:"+secret)))[:32]))
	b.WriteString("$cfg['VersionCheck'] = false;\n$cfg['SendErrorReports'] = 'never';\n$cfg['ShowPhpInfo'] = false;\n")
	b.WriteString("$cfg['PmaNoRelation_DisableWarning'] = true;\n$cfg['ExecTimeLimit'] = 600;\n$cfg['MemoryLimit'] = '512M';\n")
	b.WriteString("$cfg['ServerDefault'] = 1;\n")
	for n, e := range engines {
		fmt.Fprintf(&b, "$cfg['Servers'][%d] = ['verbose' => %s, 'host' => '127.0.0.1', 'port' => %d, 'auth_type' => 'config', "+
			"'user' => 'root', 'password' => %s, 'compress' => false, 'AllowNoPassword' => false];\n",
			n+1, phpQuote(fmt.Sprintf("%s %s (127.0.0.1:%d)", e.Name, e.Version, e.Port)), e.Port, phpQuote(e.Password()))
	}
	return b.String(), nil
}

// writePMAConfig writes config.inc.php in place (same inode, so the running
// container's bind mount sees it). It holds root passwords: readable by
// root and the container's www-data group (33) only.
func writePMAConfig(path, body string) error {
	if err := os.WriteFile(path, []byte(body), 0o640); err != nil {
		return err
	}
	os.Chown(path, 0, 33)
	return os.Chmod(path, 0o640)
}

// preparePMA writes phpMyAdmin's Apache and application config.
func (sv *Service) preparePMA(ctx context.Context, i Installed, dir string) error {
	conf := filepath.Join(dir, "conf")
	if err := os.Chmod(conf, 0o750); err != nil {
		return err
	}
	ports := fmt.Sprintf("# Generated by lmcwhm: loopback only, served by the panel under %s/.\nListen 127.0.0.1:%d\n", PMAPrefix, i.Port)
	site := fmt.Sprintf(`<VirtualHost 127.0.0.1:%d>
    ServerName localhost
    DocumentRoot /var/www/html
    Alias %s /var/www/html
    <Directory /var/www/html>
        Options FollowSymLinks
        AllowOverride None
        Require all granted
    </Directory>
</VirtualHost>
`, i.Port, PMAPrefix)
	if err := os.WriteFile(filepath.Join(conf, "ports.conf"), []byte(ports), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(conf, "site.conf"), []byte(site), 0o644); err != nil {
		return err
	}
	body, err := sv.pmaConfig(ctx, i.secret)
	if err != nil {
		return err
	}
	return writePMAConfig(filepath.Join(conf, "config.inc.php"), body)
}

// RefreshPMA rewrites phpMyAdmin's server list after engines change.
func (sv *Service) RefreshPMA(ctx context.Context) error {
	all, err := sv.list(ctx, "WHERE app = 'phpmyadmin'")
	if err != nil || len(all) == 0 {
		return err
	}
	i := all[0]
	body, err := sv.pmaConfig(ctx, i.secret)
	if err != nil {
		return err
	}
	return writePMAConfig(filepath.Join(sv.dir(i.App, i.Version), "conf", "config.inc.php"), body)
}

func (sv *Service) pmaArgs(i Installed) []string {
	conf := filepath.Join(sv.dir(i.App, i.Version), "conf")
	return []string{
		"--network", "host", "-e", "UPLOAD_LIMIT=512M",
		"-v", filepath.Join(conf, "ports.conf") + ":/etc/apache2/ports.conf:ro",
		"-v", filepath.Join(conf, "site.conf") + ":/etc/apache2/sites-available/000-default.conf:ro",
		"-v", filepath.Join(conf, "config.inc.php") + ":/etc/phpmyadmin/config.inc.php:ro",
		i.Image,
	}
}
