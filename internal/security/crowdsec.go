// CrowdSec runs the security engine (log parsing, scenarios, local API) in a
// container on the host network; the panel itself is the bouncer: it polls
// the decision stream and enforces bans in the firewall's ban sets.

const (
	CrowdSecImage = "crowdsecurity/crowdsec:v1.8.1"
	CrowdSecName  = "lmcwhm-crowdsec"
	// LAPIPort: the image's default 8080 is taken by nginx.
	LAPIPort    = 8085
	csKey       = "crowdsec"
	defaultColl = "crowdsecurity/linux crowdsecurity/sshd crowdsecurity/nginx crowdsecurity/base-http-scenarios crowdsecurity/http-cve"
)

var (
	ErrCSNotInstalled = errors.New("crowdsec.not_installed")
	ErrCSBadIP        = errors.New("crowdsec.invalid_ip")
)

type CSConfig struct {
	Installed bool   `json:"installed"`
	Community bool   `json:"community"` // share signals / receive the community blocklist (CAPI)
	Key       string `json:"key,omitempty"`
}

type CrowdSec struct {
	st    *store.Store
	box   *secrets.Box
	env   *webenv.Env
	tasks *tasks.Manager
	fw    *firewall.Service
	Home  string // /opt/lmcwhm

	mu       sync.Mutex
	lastPoll time.Time
	pollErr  string
	startup  bool
}

func NewCrowdSec(st *store.Store, box *secrets.Box, env *webenv.Env, tm *tasks.Manager, fw *firewall.Service, home string) *CrowdSec {
	return &CrowdSec{st: st, box: box, env: env, tasks: tm, fw: fw, Home: home, startup: true}
}

func (c *CrowdSec) dir() string { return filepath.Join(c.Home, "apps", "crowdsec") }

func (c *CrowdSec) Config(ctx context.Context) CSConfig {
	var cfg CSConfig
	var raw string
	if c.st.DB.QueryRowContext(ctx, `SELECT value FROM settings WHERE key = ?`, csKey).Scan(&raw) == nil {
		json.Unmarshal([]byte(raw), &cfg)
		if cfg.Key != "" {
			cfg.Key, _ = c.box.Open(cfg.Key)
		}
	}
	return cfg
}

func (c *CrowdSec) save(ctx context.Context, cfg CSConfig) error {
	if cfg.Key != "" {
		cfg.Key = c.box.Seal(cfg.Key)
	}
	b, _ := json.Marshal(cfg)
	_, err := c.st.DB.ExecContext(ctx, `INSERT INTO settings(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value`, csKey, string(b))
	return err
}

func (c *CrowdSec) args(cfg CSConfig) []string {
	d := c.dir()
	community := "true"
	if cfg.Community {
		community = "false"
	}
	return []string{
		"--network", "host",
		"-e", "COLLECTIONS=" + defaultColl,
		"-e", "BOUNCER_KEY_lmcwhm=" + cfg.Key,
		"-e", fmt.Sprintf("LOCAL_API_URL=http://127.0.0.1:%d", LAPIPort),
		"-e", "DISABLE_ONLINE_API=" + community,
		"-v", filepath.Join(d, "config") + ":/etc/crowdsec",
		"-v", filepath.Join(d, "data") + ":/var/lib/crowdsec/data",
		"-v", c.env.WWWLogs + ":" + c.env.WWWLogs + ":ro",
		"-v", "/var/log:/var/log/host:ro",
		CrowdSecImage,
	}
}

// prepare writes the overrides merged over the image's config and the log
// sources: website access / error logs and the host's auth.log.
func (c *CrowdSec) prepare() error {
	d := c.dir()
	for _, sub := range []string{"config/acquis.d", "data"} {
		if err := os.MkdirAll(filepath.Join(d, sub), 0o750); err != nil {
			return err
		}
	}
	local := fmt.Sprintf(`# Generated by lmcwhm: merged over config.yaml.
api:
  server:
    listen_uri: 127.0.0.1:%d
prometheus:
  listen_addr: 127.0.0.1
  listen_port: 6065
`, LAPIPort)
	acquis := fmt.Sprintf(`# Generated by lmcwhm.
filenames:
  - %s/*.log
labels:
  type: nginx
---
filenames:
  - /var/log/host/auth.log
labels:
  type: syslog
`, c.env.WWWLogs)
	if err := os.WriteFile(filepath.Join(d, "config", "config.yaml.local"), []byte(local), 0o640); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(d, "config", "acquis.d", "lmcwhm.yaml"), []byte(acquis), 0o640)
}

// Install starts CrowdSec (task); community enables the Central API.
func (c *CrowdSec) Install(ctx context.Context, community bool) string {
	return c.tasks.Start("crowdsec.install", func(ctx context.Context, log tasks.Logf) error {
		if !dockerx.Available(ctx) {
			return dockerx.ErrNoDocker
		}
		cfg := c.Config(ctx)
		cfg.Community = community
		if cfg.Key == "" {
			cfg.Key = settings.RandomString(40, settings.Alnum)
		}
		if !dockerx.ImageExists(ctx, CrowdSecImage) {
			log("pulling %s", CrowdSecImage)
			if _, err := dockerx.Run(ctx, "pull", "-q", CrowdSecImage); err != nil {
				return err
			}
		}
		if err := c.prepare(); err != nil {
			return err
		}
		log("starting %s (local API on 127.0.0.1:%d)", CrowdSecName, LAPIPort)
		if err := webenv.EnsureContainer(ctx, log, CrowdSecName, c.args(cfg), nil, true); err != nil {
			return err
		}
		log("waiting for the local API (first start downloads the hub collections)")
		if err := c.waitLAPI(ctx, cfg.Key, 4*time.Minute); err != nil {
			return fmt.Errorf("%w: %s", err, dockerx.Logs(ctx, CrowdSecName, 30))
		}
		cfg.Installed = true
		c.mu.Lock()
		c.startup = true
		c.mu.Unlock()
		log("CrowdSec is running; decisions are enforced by the panel firewall")
		return c.save(ctx, cfg)
	})
}

func (c *CrowdSec) Uninstall(ctx context.Context) string {
	return c.tasks.Start("crowdsec.uninstall", func(ctx context.Context, log tasks.Logf) error {
		log("removing %s", CrowdSecName)
		dockerx.Remove(ctx, CrowdSecName)
		cfg := c.Config(ctx)
		cfg.Installed = false
		if err := c.save(ctx, cfg); err != nil {
			return err
		}
		// Bans it issued are lifted with it.
		ips, _ := c.fw.IPs(ctx, "block")
		var remove []string
		for _, x := range ips {
			if x.Source == "crowdsec" {
				remove = append(remove, x.IP)
			}
		}
		return c.fw.SyncBans(ctx, "crowdsec", nil, remove)
	})
}

func (c *CrowdSec) lapi(ctx context.Context, key, path string, out any) error {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	req, _ := http.NewRequestWithContext(ctx, http.MethodGet, fmt.Sprintf("http://127.0.0.1:%d%s", LAPIPort, path), nil)
	req.Header.Set("X-Api-Key", key)
	res, err := http.DefaultClient.Do(req)
	if err != nil {
		return err
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		b, _ := io.ReadAll(io.LimitReader(res.Body, 512))
		return fmt.Errorf("crowdsec LAPI %s: %s", res.Status, strings.TrimSpace(string(b)))
	}
	if out == nil {
		return nil
	}
	return json.NewDecoder(res.Body).Decode(out)
}

func (c *CrowdSec) waitLAPI(ctx context.Context, key string, d time.Duration) error {
	deadline := time.Now().Add(d)
	var err error
	for time.Now().Before(deadline) {
		if err = c.lapi(ctx, key, "/v1/decisions?ip=127.0.0.1", nil); err == nil {
			return nil
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(3 * time.Second):
		}
	}
	return err
}

type decision struct {
	Value    string `json:"value"`
	Scope    string `json:"scope"`
	Type     string `json:"type"`
	Duration string `json:"duration"`
	Scenario string `json:"scenario"`
	Origin   string `json:"origin"`
}

// Poll pulls the decision stream once and mirrors bans into the firewall.
func (c *CrowdSec) Poll(ctx context.Context) error {
	cfg := c.Config(ctx)
	if !cfg.Installed {
		return nil
	}
	c.mu.Lock()
	startup := c.startup
	c.mu.Unlock()
	var stream struct {
		New     []decision `json:"new"`
		Deleted []decision `json:"deleted"`
	}
	err := c.lapi(ctx, cfg.Key, fmt.Sprintf("/v1/decisions/stream?startup=%v", startup), &stream)
	c.mu.Lock()
	c.lastPoll = time.Now()
	c.pollErr = ""
	if err != nil {
		c.pollErr = err.Error()
	} else {
		c.startup = false
	}
	c.mu.Unlock()
	if err != nil {
		return err
	}
	var remove []string
	for _, d := range stream.Deleted {
		if d.Type == "ban" {
			remove = append(remove, d.Value)
		}
	}
	var add []firewall.Ban
	for _, d := range stream.New {
		if d.Type != "ban" || (d.Scope != "Ip" && d.Scope != "Range") {
			continue
		}
		if ttl, err := time.ParseDuration(d.Duration); err == nil && ttl > 0 {
			add = append(add, firewall.Ban{IP: d.Value, TTL: ttl, Remark: d.Scenario})
		}
	}
	return c.fw.SyncBans(ctx, "crowdsec", add, remove)
}

// Run keeps the bouncer polling every 10 seconds.
func (c *CrowdSec) Run(ctx context.Context, logf func(string, ...any)) {
	t := time.NewTicker(10 * time.Second)
	defer t.Stop()
	for {
		if err := c.Poll(ctx); err != nil && dockerx.State(ctx, CrowdSecName) == "running" {
			logf("crowdsec poll", "err", err)
		}
		select {
		case <-ctx.Done():
			return
		case <-t.C:
		}
	}
}

// Boot recreates the container when its settings changed after an upgrade.
func (c *CrowdSec) Boot(ctx context.Context) {
	cfg := c.Config(ctx)
	if !cfg.Installed || dockerx.State(ctx, CrowdSecName) == "" {
		return
	}
	if err := c.prepare(); err == nil {
		webenv.EnsureContainer(ctx, func(string, ...any) {}, CrowdSecName, c.args(cfg), nil, false)
	}
}

type CSStatus struct {
	Installed bool   `json:"installed"`
	State     string `json:"state"`
	Community bool   `json:"community"`
	LastPoll  int64  `json:"last_poll"`
	PollError string `json:"poll_error,omitempty"`
	Bans      int    `json:"bans"`
}

func (c *CrowdSec) Status(ctx context.Context) CSStatus {
	cfg := c.Config(ctx)
	st := CSStatus{Installed: cfg.Installed, Community: cfg.Community}
	if cfg.Installed {
		st.State = dockerx.State(ctx, CrowdSecName)
	}
	c.mu.Lock()
	if !c.lastPoll.IsZero() {
		st.LastPoll = c.lastPoll.Unix()
	}
	st.PollError = c.pollErr
	c.mu.Unlock()
	c.st.DB.QueryRowContext(ctx, `SELECT COUNT(*) FROM fw_ips WHERE source = 'crowdsec' AND (expires_at = 0 OR expires_at > ?)`, time.Now().Unix()).Scan(&st.Bans)
	return st
}

func (c *CrowdSec) cscli(ctx context.Context, args ...string) (string, error) {
	if dockerx.State(ctx, CrowdSecName) != "running" {
		return "", ErrCSNotInstalled
	}
	return dockerx.Run(ctx, append([]string{"exec", CrowdSecName, "cscli"}, args...)...)
}

// Alerts returns `cscli alerts list` as JSON (raw, passed to the UI).
func (c *CrowdSec) Alerts(ctx context.Context, limit int) (json.RawMessage, error) {
	out, err := c.cscli(ctx, "alerts", "list", "-o", "json", "-l", fmt.Sprint(limit))
	if err != nil {
		return nil, err
	}
	if strings.TrimSpace(out) == "null" || out == "" {
		out = "[]"
	}
	return json.RawMessage(out), nil
}

func (c *CrowdSec) Collections(ctx context.Context) (json.RawMessage, error) {
	out, err := c.cscli(ctx, "collections", "list", "-o", "json")
	if err != nil {
		return nil, err
	}
	return json.RawMessage(out), nil
}

// AddDecision bans an address through CrowdSec (and so the firewall).
func (c *CrowdSec) AddDecision(ctx context.Context, ip string, d time.Duration, reason string) error {
	_, norm, err := firewall.NormIP(ip)
	if err != nil {
		return ErrCSBadIP
	}
	flag := "--ip"
	if strings.Contains(norm, "/") {
		flag = "--range"
	}
	if reason == "" {
		reason = "manual (lmcwhm)"
	}
	_, err = c.cscli(ctx, "decisions", "add", flag, norm, "--duration", d.String(), "--reason", reason)
	if err == nil {
		err = c.Poll(ctx)
	}
	return err
}

func (c *CrowdSec) DeleteDecision(ctx context.Context, ip string) error {
	_, norm, err := firewall.NormIP(ip)
	if err != nil {
		return ErrCSBadIP
	}
	flag := "--ip"
	if strings.Contains(norm, "/") {
		flag = "--range"
	}
	if _, err := c.cscli(ctx, "decisions", "delete", flag, norm); err != nil {
		return err
	}
	return c.Poll(ctx)
}
